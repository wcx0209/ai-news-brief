def _mapping(value):
    return value if isinstance(value, Mapping) else {}


def _text(value, fallback=""):
    return value.strip() if isinstance(value, str) and value.strip() else fallback


def _esc(value):
    return escape(str(value), quote=True)


def _locale(locale):
    if locale not in COPY:
        raise ValueError("locale must be 'en' or 'zh'")
    return locale


def _rows(value):
    return [row for row in value if isinstance(row, Mapping)] if isinstance(value, (list, tuple)) else []


def _catalog(catalog):
    result = {}
    for row in _rows(catalog):
        identifier = _text(row.get("id"))
        if identifier and identifier not in result:
            result[identifier] = row
    return result


def _evidence_ids(value):
    return list(dict.fromkeys(identifier for item in value if (identifier := _text(item)))) if isinstance(value, (list, tuple)) else []


def _date_text(value, missing):
    value = _text(value)
    try:
        if re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
            return date.fromisoformat(value).isoformat()
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        return parsed.isoformat(timespec="seconds")
    except (ValueError, TypeError):
        return missing


def _source(row, locale):
    c = COPY[locale]
    localized = _mapping(row.get(locale))
    return {
        "title": _text(localized.get("title"), c["untitled"]),
        "source": _text(row.get("source"), c["missing"]),
        "domain": _text(_mapping(row.get("domain_labels")).get(locale), _text(row.get("domain"), c["missing"])),
        "published": _date_text(row.get("published_at"), c["missing"]),
        "url": normalize_source_url(row.get("url")),
        "archive": normalize_source_url(row.get(f"archive_url_{locale}")),
    }


def _sources_html(ids, catalog, locale):
    c = COPY[locale]
    ids = _evidence_ids(ids)
    if not ids:
        return f'<aside class="source-index"><h4>{c["evidence"]}</h4><p class="missing">{c["no_evidence"]}</p></aside>'
    entries = []
    for identifier in ids:
        row = catalog.get(identifier)
        if row is None:
            entries.append(f'<li class="missing">{c["missing_evidence"]}: <code>{_esc(identifier)}</code></li>')
            continue
        source = _source(row, locale)
        links = []
        for key, label, missing in (("url", "original", "unsafe_original"), ("archive", "archive", "unsafe_archive")):
            links.append(f'<a href="{_esc(source[key])}" target="_blank" rel="noopener noreferrer">{c[label]}</a>' if source[key] else f'<span class="missing">{c[missing]}</span>')
        entries.append(f'<li><span class="source-title">{_esc(source["title"])}</span><span class="source-meta">{c["source"]}: {_esc(source["source"])} · {c["published"]}: {_esc(source["published"])} · {c["domain"]}: {_esc(source["domain"])}</span><div class="source-links">{"".join(links)}</div><span class="event-id">{_esc(identifier)}</span></li>')
    return f'<aside class="source-index"><h4>{c["evidence"]}</h4><ol>{"".join(entries)}</ol></aside>'


def _event_html(event, catalog, locale):
    c = COPY[locale]
    sections = []
    for key, label in (("what_changed", "what"), ("why_it_matters", "why"), ("uncertainty", "uncertainty")):
        text = _text(event.get(key), c["uncertainty_missing"] if key == "uncertainty" else c["missing"])
        attrs = ' class="uncertainty"' if key == "uncertainty" else ""
        sections.append(f'<div{attrs}><strong class="reading-label">{c[label]}</strong><p>{_esc(text)}</p></div>')
    identifier = _text(event.get("event_id"))
    identifier_markup = f'<p class="event-id">{_esc(identifier)}</p>' if identifier else ""
    return f'<article>{identifier_markup}<h3>{_esc(_text(event.get("title"), c["untitled"]))}</h3>{"".join(sections)}{_sources_html(event.get("evidence_ids"), catalog, locale)}</article>'


def _coverage_rows(report):
    coverage = report.get("coverage")
    return _rows(_mapping(coverage).get("fields")) if isinstance(coverage, Mapping) else _rows(coverage)


def _count(value, missing):
    return str(value) if isinstance(value, int) and not isinstance(value, bool) and value >= 0 else missing


def _coverage_html(report, locale):
    rows = _coverage_rows(report)
    if not rows:
        return ""
    c = COPY[locale]
    cells = []
    for row in rows:
        label = _text(_mapping(row.get("domain_labels")).get(locale), _text(row.get("domain"), c["missing"]))
        cells.append(f'<tr><td>{_esc(label)}</td><td>{_count(row.get("qualified_count"), c["missing"])}</td><td>{_count(row.get("selected_count"), c["missing"])}</td></tr>')
    return f'<section><h2>{c["coverage"]}</h2><p class="section-note">{c["coverage_note"]}</p><table><thead><tr><th scope="col">{c["domain"]}</th><th scope="col">{c["qualified"]}</th><th scope="col">{c["selected"]}</th></tr></thead><tbody>{"".join(cells)}</tbody></table></section>'


def _issue_meta(report, locale):
    c = COPY[locale]
    issue = _mapping(report.get("issue"))
    start = _date_text(issue.get("week_start") or issue.get("start"), c["missing"])
    end = _date_text(issue.get("week_end") or issue.get("end"), c["missing"])
    exact_start = _date_text(issue.get("start"), c["missing"])
    exact_end = _date_text(issue.get("end"), c["missing"])
    return [(c["window"], f"{start} — {end}"),
            (c["timezone"], _text(issue.get("timezone"), c["missing"])),
            (c["generated"], _date_text(issue.get("generated_at"), c["missing"])),
            (c["window"], f"{exact_start} → {exact_end}")]


def _synthesis(content):
    """Old reports do not acquire a made-up interpretation during rendering."""
    synthesis = _mapping(content.get("synthesis"))
    values = [synthesis.get("intro"), synthesis.get("limits")]
    for key in ("signal", "structure", "consequence"):
        point = _mapping(synthesis.get(key))
        values.extend((point.get("title"), point.get("text")))
    return synthesis if any(_text(value) for value in values) else None


def _synthesis_html(content, catalog, locale):
    synthesis = _synthesis(content)
    if synthesis is None:
        return ""
    c = COPY[locale]
    points = []
    for key in ("signal", "structure", "consequence"):
        point = _mapping(synthesis.get(key))
        title = _text(point.get("title"))
        title_html = f'<h4>{_esc(title)}</h4>' if title else ""
        support = f'<p class="synthesis-support" role="note">{c["synthesis_insufficient"]}</p>' if point.get("support") == "insufficient" else ""
        points.append(f'<div class="synthesis-point" data-synthesis-dimension="{key}"><h3>{c["synthesis_" + key]}</h3>{title_html}{support}<p>{_esc(_text(point.get("text"), c["missing"]))}</p>{_synthesis_sources_html(point.get("evidence_ids"), catalog, locale)}</div>')
    references = _synthesis_sources_html(synthesis.get("evidence_ids"), catalog, locale) if _evidence_ids(synthesis.get("evidence_ids")) else ""
    return (f'<section class="synthesis" aria-labelledby="weekly-synthesis-title"><h2 id="weekly-synthesis-title">{c["synthesis"]}</h2>'
            f'<p class="section-note">{c["synthesis_note"]}</p><p class="synthesis-intro">{_esc(_text(synthesis.get("intro"), c["missing"]))}</p>'
            f'{"".join(points)}<div class="synthesis-limits"><strong>{c["synthesis_limits"]}</strong><p>{_esc(_text(synthesis.get("limits"), c["uncertainty_missing"]))}</p></div>{references}</section>')


def _synthesis_sources_html(ids, catalog, locale):
    return (f'<details class="synthesis-sources"><summary>{COPY[locale]["synthesis_sources"]}</summary>'
            f'{_sources_html(ids, catalog, locale)}</details>')


def _html(report, catalog, locale):
    c = COPY[locale]
    content = _mapping(report.get(locale))
    title = _text(content.get("title"), c["title"])
    lead = _mapping(content.get("lead"))
    meta = "".join(f'<p><strong>{label}</strong><br>{_esc(value)}</p>' for label, value in _issue_meta(report, locale))
    body = [f'<section><h2>{c["lead"]}</h2><p class="lead-text">{_esc(_text(lead.get("text"), c["missing"]))}</p>{_sources_html(lead.get("evidence_ids"), catalog, locale)}</section>']
    for key, label in (("main_events", "main"), ("early_signals", "signals")):
        rows = _rows(content.get(key))
        note = f'<p class="section-note">{c["signal_note"]}</p>' if key == "early_signals" else ""
        entries = "".join(_event_html(row, catalog, locale) for row in rows) if rows else f'<p class="missing">{c["empty"]}</p>'
        body.append(f'<section><h2>{c[label]}</h2>{note}{entries}</section>')
    follow = _mapping(content.get("follow_up"))
    available = follow.get("available")
    status = c["follow_available"] if available is True else c["follow_unavailable"] if available is False else c["follow_unknown"]
    follow_rows = _rows(follow.get("items")) if available is True else []
    follow_body = "".join(_event_html(row, catalog, locale) for row in follow_rows)
    if available is True and not follow_rows:
        follow_body = f'<p class="missing">{c["follow_incomplete"]}</p>'
    body.append(f'<section><h2>{c["follow"]}</h2><p class="section-note">{status}</p><p>{_esc(_text(follow.get("note"), c["missing"]))}</p>{follow_body}</section>')
    watch = _rows(content.get("next_watch"))
    watch_body = "".join(f'<li><p>{_esc(_text(row.get("text"), c["missing"]))}</p>{_sources_html(row.get("evidence_ids"), catalog, locale)}</li>' for row in watch)
    watch_markup = f'<ol class="watch-list">{watch_body}</ol>' if watch else f'<p class="missing">{c["empty"]}</p>'
    body.append(f'<section><h2>{c["watch"]}</h2>{watch_markup}</section>')
    other = "en" if locale == "zh" else "zh"
    return f'''<!doctype html>
<html lang="{c['lang']}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'"><meta name="robots" content="noindex,nofollow"><title>{_esc(title)} | Polyemergence</title><style>{STYLE}</style></head>
<body><main class="page"><header class="masthead"><span class="wordmark">POLYEMERGENCE</span><a class="locale-link" href="{other}.html" hreflang="{COPY[other]['lang']}">{'EN' if other == 'en' else '中'}</a></header>
<p class="status">{c['draft']}</p><h1>{_esc(title)}</h1><p class="dek">{_esc(_text(content.get('dek'), c['missing']))}</p><div class="issue-meta">{meta}</div>
{_synthesis_html(content, catalog, locale)}{''.join(body)}{_coverage_html(report, locale)}<footer><p>{c['footer']}</p><p>{c['publisher']}</p></footer></main></body></html>'''


def render_review(report, catalog):
    """Return independent ``{'zh': html, 'en': html}`` review documents.

    Save these as ``zh.html`` / ``en.html`` if reciprocal language links are
    wanted. Inputs are never changed, and no publication side effect occurs.
    """
    report = _mapping(report)
    evidence = _catalog(catalog)
    return {locale: _html(report, evidence, locale) for locale in ("zh", "en")}


def _md(value):
    # HTML is inert even in Markdown renderers that allow embedded HTML. Escape
    # Markdown syntax too: input summaries must not manufacture extra links.
    return re.sub(r"([\\`*_{}\[\]()#+.!|>~+\-])", r"\\\1", escape(str(value), quote=False))


def _md_link(label, url):
    url = url.replace("<", "%3C").replace(">", "%3E")
    return f"[{label}](<{url}>)"


def _sources_md(ids, catalog, locale):
    c = COPY[locale]
    ids = _evidence_ids(ids)
    if not ids:
        return c["no_evidence"]
    lines = [f'**{c["evidence"]}**']
    for identifier in ids:
        row = catalog.get(identifier)
        if row is None:
            lines.append(f'- {c["missing_evidence"]}: {_md(identifier)}')
            continue
        source = _source(row, locale)
        links = [(_md_link(c[label], source[key]) if source[key] else c[missing])
                 for key, label, missing in (("url", "original", "unsafe_original"), ("archive", "archive", "unsafe_archive"))]
        lines.append(f'- {_md(source["title"])} · {c["source"]}: {_md(source["source"])} · {c["published"]}: {_md(source["published"])} · {c["domain"]}: {_md(source["domain"])} · {" / ".join(links)} · {_md(identifier)}')
    return "\n".join(lines)


def _event_md(event, catalog, locale):
    c = COPY[locale]
    lines = ["### " + _md(_text(event.get("title"), c["untitled"]))]
    for key, label in (("what_changed", "what"), ("why_it_matters", "why"), ("uncertainty", "uncertainty")):
        value = _text(event.get(key), c["uncertainty_missing"] if key == "uncertainty" else c["missing"])
        lines.append(f'**{c[label]}**\n\n{_md(value)}')
    lines.append(_sources_md(event.get("evidence_ids"), catalog, locale))
    return "\n\n".join(lines)


def _synthesis_md(content, catalog, locale):
    synthesis = _synthesis(content)
    if synthesis is None:
        return ""
    c = COPY[locale]
    lines = ["## " + c["synthesis"], c["synthesis_note"], _md(_text(synthesis.get("intro"), c["missing"]))]
    for key in ("signal", "structure", "consequence"):
        point = _mapping(synthesis.get(key))
        lines.append("### " + c["synthesis_" + key])
        title = _text(point.get("title"))
        if title:
            lines.append("**" + _md(title) + "**")
        if point.get("support") == "insufficient":
            lines.append("**" + c["synthesis_insufficient"] + "**")
        lines.extend([_md(_text(point.get("text"), c["missing"])), _sources_md(point.get("evidence_ids"), catalog, locale)])
    lines.extend(["### " + c["synthesis_limits"], _md(_text(synthesis.get("limits"), c["uncertainty_missing"]))])
    if _evidence_ids(synthesis.get("evidence_ids")):
        lines.append(_sources_md(synthesis.get("evidence_ids"), catalog, locale))
    return "\n\n".join(lines)


def to_markdown(report, locale, catalog):
    """Render one locale, retaining claim/interpretation/uncertainty boundaries."""
    locale = _locale(locale)
    report, catalog = _mapping(report), _catalog(catalog)
    c = COPY[locale]
    content = _mapping(report.get(locale))
    lead = _mapping(content.get("lead"))
    lines = ["# " + _md(_text(content.get("title"), c["title"])), c["draft"],
             _md(_text(content.get("dek"), c["missing"]))]
    lines.extend(f'**{label}:** {_md(value)}' for label, value in _issue_meta(report, locale))
    synthesis = _synthesis_md(content, catalog, locale)
    if synthesis:
        lines.append(synthesis)
    lines.extend(["## " + c["lead"], _md(_text(lead.get("text"), c["missing"])), _sources_md(lead.get("evidence_ids"), catalog, locale)])
    for key, label in (("main_events", "main"), ("early_signals", "signals")):
        lines.append("## " + c[label])
        if key == "early_signals":
            lines.append(c["signal_note"])
        rows = _rows(content.get(key))
        if rows:
            lines.extend(_event_md(row, catalog, locale) for row in rows)
        else:
            lines.append(c["empty"])
    follow = _mapping(content.get("follow_up"))
    available = follow.get("available")
    lines.extend(["## " + c["follow"], c["follow_available"] if available is True else c["follow_unavailable"] if available is False else c["follow_unknown"], _md(_text(follow.get("note"), c["missing"]))])
    rows = _rows(follow.get("items")) if available is True else []
    if rows:
        lines.extend(_event_md(row, catalog, locale) for row in rows)
    elif available is True:
        lines.append(c["follow_incomplete"])
    lines.append("## " + c["watch"])
    watch = _rows(content.get("next_watch"))
    if watch:
        for row in watch:
            text = _md(_text(row.get("text"), c["missing"])).replace("\n", "\n  ")
            sources = _sources_md(row.get("evidence_ids"), catalog, locale)
            # Keep evidence inside its watch item rather than making the
            # citation bullets look like additional top-level watch items.
            nested_sources = "\n".join("  " + line if line else "" for line in sources.splitlines())
            lines.append("- " + text + "\n\n" + nested_sources)
    else:
        lines.append(c["empty"])
    coverage = _coverage_rows(report)
    if coverage:
        lines.extend(["## " + c["coverage"], c["coverage_note"]])
        table = [f'| {c["domain"]} | {c["qualified"]} | {c["selected"]} |', "| --- | ---: | ---: |"]
        for row in coverage:
            label = _text(_mapping(row.get("domain_labels")).get(locale), _text(row.get("domain"), c["missing"]))
            label = re.sub(r"[\r\n]+", " ", label)
            table.append(f'| {_md(label)} | {_count(row.get("qualified_count"), c["missing"])} | {_count(row.get("selected_count"), c["missing"])} |')
        # Blank lines between table rows terminate a GFM table. The outer
        # document still uses paragraph spacing between complete blocks.
        lines.append("\n".join(table))
    lines.extend(["---", c["footer"], c["publisher"]])
    return "\n\n".join(lines) + "\n"
